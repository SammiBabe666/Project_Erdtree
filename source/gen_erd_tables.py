#!/usr/bin/env python3
"""Generate erd_tables.h, the three lookup tables erdtree.c renders from:

  warp_cols[257][65]  Brassophone's exponential phase warp (gen_warp_table.py, from Brassophone by nvmsocool),
                      stored column by column: warp_cols[t][s] = warp_table[s][t], with s = 64 repeating full
                      phase. A note's brass timbre column changes slowly, so its 65 values sit in a few cache lines
                      instead of 64 rows apart, and the interpolation needs no end-of-row test.
  erd_sine[1025]      one sine cycle in 1024 steps plus a guard point (Q15), read with linear interpolation: the
                      brass tone and the choir's shimmer harmonic.
  choir_wave[1025]    one cycle of the choir in 1024 steps plus a guard point: harmonics 1 to 4 with weights 4500,
                      9000, 6500 and 4000 (Q15), read with linear interpolation. Harmonic 6 (the shimmer) is read
                      from erd_sine, as its weight moves with the slow LFO.
The two small tables (4 KiB together) replace the firmware's 16 KiB sine table and an 8192-step choir wave (v0.4):
read at scattered points every sample, those 32 KiB did not stay in the Blackfin's data cache.

    python3 gen_erd_tables.py > erd_tables.h
Copyright (C) 2026 Sammi (Project ERD). GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math

ROWS, COLUMNS, MAX_TIMBRE = 64, 256, 20      # as gen_warp_table.py
CHOIR = [(1, 4500), (2, 9000), (3, 6500), (4, 4000)]
STEPS = 1024                                 # erd_sine and choir_wave: steps per cycle (then one guard point)


def warp(ph_f, timbre):
    """gen_warp_table.py's warp: normalized phase ph_f in [0, 1] warped toward the centre by timbre."""
    if abs(timbre) < 0.01:
        return ph_f
    x = 2.0 * ph_f - 1.0
    w = (math.exp(-timbre * abs(x)) - 1.0) / (math.exp(-timbre) - 1.0)
    return max(0.0, min(1.0, 0.5 * (w if x >= 0 else -w) + 0.5))


def q15(v):
    return int(max(0.0, min(1.0, v)) * 32767)          # truncating, as gen_warp_table.py


def main():
    lines = ["/* Generated by gen_erd_tables.py: do not edit. */",
             "/* warp_cols[t][s]: Brassophone's warp table by column, t = 0..256 (timbre 0..20), s = 0..64 (phase) */",
             "static const int16_t warp_cols[257][65] = {"]
    for t in range(COLUMNS + 1):
        timbre = t * MAX_TIMBRE / COLUMNS
        col = [q15(warp(s / (ROWS - 1), timbre)) for s in range(ROWS)] + [32767]
        lines.append("    {")
        for i in range(0, len(col), 13):
            lines.append("        " + ", ".join(f"{v:5d}" for v in col[i:i + 13]) + ",")
        lines.append("    },")
    lines.append("};")
    tables = (("erd_sine", "sine, Q15", [round(32767 * math.sin(2 * math.pi * k / STEPS)) for k in range(STEPS)]),
              ("choir_wave", "harmonics 1..4",
               [round(sum(w * math.sin(2 * math.pi * h * k / STEPS) for h, w in CHOIR) * 32767 / 32768)
                for k in range(STEPS)]))
    for name, what, wave in tables:
        wave = wave + wave[:1]                               # guard point: index 1024 = index 0
        lines.append(f"/* {name}[k]: {what}, one cycle in {STEPS} steps, k = 0..{STEPS} (k = {STEPS} repeats k = 0) */")
        lines.append(f"static const int16_t {name}[{STEPS + 1}] = {{")
        for i in range(0, len(wave), 16):
            lines.append("    " + ", ".join(f"{v:6d}" for v in wave[i:i + 16]) + ",")
        lines.append("};")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
