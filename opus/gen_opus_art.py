#!/usr/bin/env python3
"""Generate opus/sammi.erdtree/erd_art.h for the Opus 2 port: the Erdtree screen of ../source/gen_svg.py split in two.

  erd_art     the parts that never move (the trunk, the ground, the ruins: gen_svg's "white" and "blue" groups) as an
              SVG string. The plugin writes it to its folder (opus_art_text), has the OS draw it once and keeps the
              pixels. White and blue are placeholders (ART_WHITE_RGB, ART_BLUE_RGB) the page recolours to the white
              and blue encoders' colours.
  crown_*     the crown (gen_svg's "green" group) as polylines, its curves cut into CURVE_STEPS lines each, in units
              x 64. The page scales and turns it about the top of the trunk every frame and draws it with the core's
              smoothed lines, as erdscreen.c turned the SVG node on op1r.
    python3 opus/gen_opus_art.py > opus/sammi.erdtree/erd_art.h
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'source'))
import gen_svg  # noqa: E402

CURVE_STEPS = 6
ART_WHITE, ART_BLUE = '#FFFFFE', '#4D9EFE'


def num(s):
    return float(s)


def cubic(p0, p1, p2, p3, n):
    out = []
    for i in range(1, n + 1):
        t = i / n
        u = 1 - t
        out.append((u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0],
                    u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1]))
    return out


def crown_lines():
    svg = gen_svg.crown()
    lines = []
    for el in re.findall(r'<(polyline|path) ([^>]*)/>', svg):
        kind, attrs = el
        w = num(re.search(r'stroke-width="([^"]+)"', attrs).group(1))
        if kind == 'polyline':
            pts = [tuple(map(num, p.split(','))) for p in re.search(r'points="([^"]+)"', attrs).group(1).split()]
        else:
            d = re.search(r'd="([^"]+)"', attrs).group(1)
            m = re.fullmatch(r'M([-\d.]+),([-\d.]+) C([-\d.]+),([-\d.]+) ([-\d.]+),([-\d.]+) ([-\d.]+),([-\d.]+)', d)
            v = list(map(num, m.groups()))
            p0 = (v[0], v[1])
            pts = [p0] + cubic(p0, (v[2], v[3]), (v[4], v[5]), (v[6], v[7]), CURVE_STEPS)
        lines.append((w, pts))
    return lines


def static_svg():
    w2, b2 = gen_svg.ruins()
    white = ''.join(gen_svg.trunk() + w2).replace(gen_svg.WHITE, ART_WHITE)
    blue = ''.join(b2).replace(gen_svg.BLUE, ART_BLUE)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{gen_svg.W}" height="{gen_svg.H}" '
            f'viewBox="0 0 {gen_svg.W} {gen_svg.H}"><g id="white">{white}</g><g id="blue">{blue}</g></svg>')


def c_string(s, width=100):
    esc = lambda t: t.replace('\\', '\\\\').replace('"', '\\"')
    return '\n'.join(f'    "{esc(s[i:i + width])}"' for i in range(0, len(s), width))


def main():
    lines = crown_lines()
    pts = [p for _, ps in lines for p in ps]
    o = ['/* Generated by opus/gen_opus_art.py from source/gen_svg.py: do not edit. */',
         '#ifndef ERD_ART_H', '#define ERD_ART_H', '',
         '/* the screen\'s still parts: the trunk, the ground and the ruins */',
         'static const char erd_art[] =', c_string(static_svg()) + ';',
         f'#define ART_WHITE_RGB 0x{ART_WHITE[1:]}u      /* placeholder: the white encoder\'s colour */',
         f'#define ART_BLUE_RGB  0x{ART_BLUE[1:]}u      /* placeholder: the blue encoder\'s colour */', '',
         '/* the crown: CROWN_LINES polylines, crown_n[i] points each (from crown_pt), stroke width x 4 in crown_w */',
         f'#define CROWN_LINES {len(lines)}', f'#define CROWN_POINTS {len(pts)}',
         'static const unsigned char crown_n[CROWN_LINES] = {']
    o += ['    ' + ', '.join(str(len(ps)) for _, ps in lines[i:i + 20]) + ',' for i in range(0, len(lines), 20)]
    o += ['};', 'static const unsigned char crown_w[CROWN_LINES] = {']
    o += ['    ' + ', '.join(str(round(w * 4)) for w, _ in lines[i:i + 20]) + ',' for i in range(0, len(lines), 20)]
    o += ['};', '/* x, y in units x 64 */', 'static const short crown_pt[CROWN_POINTS][2] = {']
    for i in range(0, len(pts), 6):
        o.append('    ' + ' '.join(f'{{ {round(x * 64)}, {round(y * 64)} }},' for x, y in pts[i:i + 6]))
    o += ['};', '', '#endif', '']
    sys.stdout.write('\n'.join(o))


if __name__ == '__main__':
    main()
